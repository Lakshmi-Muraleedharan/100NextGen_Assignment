import numpy as np
import pandas as pd

#1.Load the dataset using Pandas
data= pd.read_csv("/content/diabetes.csv")

data.head()

#2a. shape dataset
print("Shape of dataset",data.shape)
print("------------------------------------------")
#2b. column name
print("Column Name",data.columns)
print("------------------------------------------")
#2c. column datatypes
print("Column datatypes", data.dtypes)
print("------------------------------------------")
#2d. missing values
print("Missing values",data.isnull().sum())
print("------------------------------------------")
#2e. basic statistic summary
print("Basic statistical value",data.describe())

data.head()

x=data.drop(['Outcome'],axis=1)
y=data['Outcome'] #output dependent column

from sklearn.model_selection import train_test_split
x_train,x_test,y_train,y_test=train_test_split(x,y,test_size=0.20)

from sklearn.preprocessing import StandardScaler#imported as numeric features are standardized using StandardScaler
sc=StandardScaler()
x_train=sc.fit_transform(x_train)
x_test=sc.fit_transform(x_test)

from sklearn.linear_model import LogisticRegression #used for classification
model=LogisticRegression()
model.fit(x_train,y_train)

predictions=model.predict(x_train)
print("Training Predictions",predictions)

from sklearn.metrics import accuracy_score
accuracy_score=accuracy_score(y_train,predictions)
print("Train Accuracy Score",accuracy_score)

test_predictions=model.predict(x_test)
from sklearn.metrics import accuracy_score
test_accuracy_score=accuracy_score(y_test,test_predictions)
print("Test Accuracy Score",test_accuracy_score)

from sklearn.metrics import classification_report
print(classification_report(y_test,test_predictions))

from sklearn.metrics import confusion_matrix
print(confusion_matrix(y_test,test_predictions))

